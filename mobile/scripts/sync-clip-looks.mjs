/**
 * Writes the App Clip's copy of the looks: `targets/clip/LooksGenerated.swift`
 * from `src/constants/looks.ts`.
 *
 * `looks.ts` is the only description of a look. The app's SkSL, the web
 * camera's WebGL and the clip's Metal shader all read the same recipes, so a
 * guest's print looks the same whichever camera took it. This script turns the
 * TypeScript into Swift literals; `plugins/with-app-clip.js` runs it on every
 * prebuild (so EAS can never build a stale copy) and the output is committed
 * so the Swift reads complete in the repository.
 *
 *   node scripts/sync-clip-looks.mjs          write the file
 *   node scripts/sync-clip-looks.mjs --check  fail if it is out of date
 */
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';

const root = fileURLToPath(new URL('..', import.meta.url));
const source = join(root, 'src/constants/looks.ts');
const target = join(root, 'targets/clip/LooksGenerated.swift');

// Transpile the module as it is (type imports vanish) and import it.
const ts = createRequire(import.meta.url)('typescript');
const js = ts.transpileModule(readFileSync(source, 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
}).outputText;
const dir = mkdtempSync(join(tmpdir(), 'left-looks-'));
let looks;
try {
  writeFileSync(join(dir, 'looks.mjs'), js);
  looks = await import(pathToFileURL(join(dir, 'looks.mjs')).href);
} finally {
  rmSync(dir, { recursive: true, force: true });
}

const { LOOKS, LOOK_RECIPES, LENS, GRAIN_CELLS, PhotoOutput, DEFAULT_LOOK } = looks;
for (const [name, value] of Object.entries({ LOOKS, LOOK_RECIPES, LENS, GRAIN_CELLS, PhotoOutput, DEFAULT_LOOK })) {
  if (value === undefined) throw new Error(`sync-clip-looks: looks.ts no longer exports ${name}`);
}

const num = (n) => {
  if (typeof n !== 'number' || !Number.isFinite(n)) throw new Error(`sync-clip-looks: not a number: ${n}`);
  return Number.isInteger(n) ? `${n}.0` : String(n);
};
const rgb = (v) => `SIMD3<Float>(${v.map(num).join(', ')})`;
const str = (s) => JSON.stringify(String(s));

const ids = Object.keys(LOOK_RECIPES);
const recipe = (id) => {
  const r = LOOK_RECIPES[id];
  return `    .${id}: LookRecipe(
      saturation: ${num(r.saturation)},
      gain: ${rgb(r.gain)},
      contrast: ${num(r.contrast)},
      shadowTint: ${rgb(r.shadowTint)},
      highlightTint: ${rgb(r.highlightTint)},
      fade: ${num(r.fade)},
      grain: ${num(r.grain)},
      vignette: ${num(r.vignette)}
    ),`;
};

const swift = `// GENERATED by mobile/scripts/sync-clip-looks.mjs from
// mobile/src/constants/looks.ts. Do not edit — change the recipe there and run
// \`node scripts/sync-clip-looks.mjs\` (prebuild runs it too).

import Foundation

/// Mirrors the \`film_look\` enum.
enum FilmLook: String, CaseIterable {
${ids.map((id) => `  case ${id}`).join('\n')}

  static let fallback: FilmLook = .${DEFAULT_LOOK}

  var name: String {
    switch self {
${LOOKS.map((l) => `    case .${l.id}: return ${str(l.name)}`).join('\n')}
    }
  }
}

enum Looks {
  static let recipes: [FilmLook: LookRecipe] = [
${ids.map(recipe).join('\n')}
  ]

  /// \`LENS.fringe\`
  static let fringe: Float = ${num(LENS.fringe)}

  /// \`GRAIN_CELLS\`
  static let grainCells: Float = ${num(GRAIN_CELLS)}
}

/// \`PhotoOutput\`: what the camera writes.
enum PhotoOutput {
  static let longEdge: Int = ${PhotoOutput.longEdge}
  static let quality: Double = ${num(PhotoOutput.quality / 100)}
  static let thumbLongEdge: Int = ${PhotoOutput.thumbLongEdge}
  static let thumbQuality: Double = ${num(PhotoOutput.thumbQuality / 100)}
}
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {}
  if (current !== swift) {
    console.error('targets/clip/LooksGenerated.swift is out of date — run node scripts/sync-clip-looks.mjs');
    process.exit(1);
  }
} else {
  writeFileSync(target, swift);
}
