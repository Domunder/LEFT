/**
 * Events, membership and clips.
 *
 * Thin wrappers over the database — no state is held here. Budget movement
 * lives in ./budget.ts and goes through the reserve/commit functions.
 */

import { subscribeToChanges } from './realtime';
import { getSupabase } from './supabase';
import type { Database } from '@/types/database';

type Tables = Database['public']['Tables'];

export type Event = Tables['events']['Row'];
export type EventMember = Tables['event_members']['Row'];
export type Clip = Tables['clips']['Row'];

export type EventType = Database['public']['Enums']['event_type'];
export type FilmFormat = Database['public']['Enums']['film_format'];

export type CreateEventInput = {
  name: string;
  eventType: EventType;
  format: FilmFormat;
  /** When the filming window closes. */
  endsAt: Date;
  /** Group-size tier: 4, 10, 25, 50, 100, 150 or 200. */
  maxMembers: number;
  /**
   * A shorter pool than the group's default, when the host picked one.
   *
   * Optional, and only ever *shorter*: `create_event()` refuses anything longer
   * than `budget_plan(max_members)`. Omitted means "use the default", which is
   * what almost every event does.
   *
   * This is the whole duration story now. It is what the group may film, shared
   * between all of them, and — since nothing is rendered — exactly how long the
   * finished playback runs. There is no second number.
   */
  budgetSeconds?: number;
  /**
   * The store transaction just made, when this event needed paying for.
   *
   * A *lookup hint*, never a claim of payment: the edge function asks RevenueCat
   * about it directly and the RPC spends a real ledger row. Omitted for groups of
   * four or fewer, which are free.
   */
  transactionId?: string;
};

/**
 * Raised when a purchase has no ledger row the server can see *yet*.
 *
 * Distinct from "never paid": the store has taken the money and RevenueCat has
 * simply not told us, so retrying shortly is the right move. Screens use this to
 * decide between waiting and asking the user to pay again.
 */
export class PurchaseUnsettledError extends Error {
  constructor() {
    super('Your purchase has not been confirmed yet');
    this.name = 'PurchaseUnsettledError';
  }
}

export function isPurchaseUnsettled(e: unknown): e is PurchaseUnsettledError {
  return e instanceof PurchaseUnsettledError;
}

/**
 * Create an event. The invite code is generated by the database, and the host is
 * added as a member by trigger — both are already on the returned row.
 *
 * Clients cannot insert into `events`: the grant was revoked, because the old RLS
 * policy checked only `host_id = auth.uid()` and so let any client mint a
 * 200-person event. `create_event()` is the only door.
 *
 * **The money is here again.** It sat on 17 for as long as there was a rendered
 * film to sell a clean copy of; with no render there was nothing left to charge
 * for after the fact, so the ask went back to where it was — 05.1, priced on the
 * group the host picks. Groups of four or fewer are free and send no transaction.
 *
 * Goes through the `create-event` edge function rather than the RPC directly:
 * `purchaseStoreProduct()` resolves the moment the store takes the money, but
 * RevenueCat's webhook is a separate async call that has usually not landed yet.
 * The function asks RevenueCat directly and writes the ledger row before the RPC
 * spends it.
 *
 * `budgetSeconds` may be omitted; the server derives it from the group size, and
 * accepts only a shorter one. That asymmetry is what keeps `lib/pricing.ts` a
 * display mirror rather than an authority.
 */
export async function createEvent(input: CreateEventInput): Promise<Event> {
  const supabase = getSupabase();

  const { data, error } = await supabase.functions.invoke<{ event: Event }>('create-event', {
    body: {
      name: input.name,
      eventType: input.eventType,
      format: input.format,
      endsAt: input.endsAt.toISOString(),
      maxMembers: input.maxMembers,
      /*
        Null rather than the computed default. Null means "use the group's plan",
        and sending the default would make this mirror of `budget_plan()`
        authoritative by accident — the one thing pricing.ts must never become.
      */
      budgetSeconds: input.budgetSeconds ?? null,
      transactionId: input.transactionId ?? null,
    },
  });

  if (error) throw await describeFunctionError(error);
  if (!data?.event) throw new Error('The event was not created');
  return data.event;
}

/**
 * Unwrap an edge-function failure into something the screen can act on.
 *
 * `functions.invoke` reports a non-2xx as a generic FunctionsHttpError and keeps
 * the body on `context`, so the `unsettled` and `anonymous` hints the RPC raised
 * are only reachable by reading it back out.
 */
async function describeFunctionError(error: unknown): Promise<Error> {
  const context = (error as { context?: Response }).context;

  if (context && typeof context.json === 'function') {
    try {
      const body = await context.json();
      if (body?.hint === 'unsettled') return new PurchaseUnsettledError();
      if (body?.error) {
        const failure = new Error(String(body.error));
        /*
          Carry the hint onto the Error. `messageFor()` reads it to rewrite the
          ones whose own message is written for a log rather than for a person —
          'anonymous' is the first — and an Error that dropped it would show the
          log sentence instead.
        */
        if (typeof body.hint === 'string') Object.assign(failure, { hint: body.hint });
        return failure;
      }
    } catch {
      // Fall through to the original error.
    }
  }
  return error instanceof Error ? error : new Error(String(error));
}

/**
 * Join by invite code.
 *
 * A function rather than a query: guests cannot read the events table until
 * they are members, so the code is resolved server-side. Throws if the code is
 * wrong, the event has ended, or the group is full.
 */
export async function joinEvent(inviteCode: string, displayName: string): Promise<string> {
  const { data, error } = await getSupabase().rpc('join_event', {
    p_invite_code: inviteCode,
    p_display_name: displayName,
  });
  if (error) throw error;
  return data;
}

export async function getEvent(eventId: string): Promise<Event> {
  const { data, error } = await getSupabase().from('events').select().eq('id', eventId).single();
  if (error) throw error;
  return data;
}

/** Every event the signed-in user belongs to — the Films library. */
export async function listMyEvents(): Promise<Event[]> {
  const { data, error } = await getSupabase()
    .from('events')
    .select()
    .order('created_at', { ascending: false });
  if (error) throw error;
  return data ?? [];
}

/** An event plus its roster size — one row per card on 15/16. */
export type EventSummary = Event & { memberCount: number };

/**
 * The Films library (15/16), in one round trip.
 *
 * Each card shows "5 people", which `listMyEvents()` cannot answer — it returns
 * events and nothing else, so a library of N events would mean N follow-up
 * `listMembers()` calls. PostgREST counts the embedded relation server-side
 * instead, which RLS permits: `events` and `event_members` are gated by the same
 * `is_event_member(...)` predicate, so counting the rosters of events you already
 * belong to reveals nothing you could not read row by row.
 *
 * `listMyEvents()` stays — screen 10 resolves its event through it.
 */
export async function listMyEventSummaries(): Promise<EventSummary[]> {
  const { data, error } = await getSupabase()
    .from('events')
    .select('*, event_members(count)')
    .order('created_at', { ascending: false });
  if (error) throw error;

  return (data ?? []).map(({ event_members, ...event }) => ({
    ...(event as Event),
    // The aggregate comes back as a one-element array, and as nothing at all for
    // an event whose roster is somehow empty.
    memberCount: (event_members as { count: number }[] | null)?.[0]?.count ?? 0,
  }));
}

export async function listMembers(eventId: string): Promise<EventMember[]> {
  const { data, error } = await getSupabase()
    .from('event_members')
    .select()
    .eq('event_id', eventId)
    .order('joined_at');
  if (error) throw error;
  return data ?? [];
}

export async function listClips(eventId: string): Promise<Clip[]> {
  const { data, error } = await getSupabase()
    .from('clips')
    .select()
    .eq('event_id', eventId)
    .order('recorded_at');
  if (error) throw error;
  return data ?? [];
}

/**
 * Storage path convention the bucket policies expect:
 * `{event_id}/{user_id}/{key}.mp4`.
 *
 * **`key` is the reservation id, not the clip id.** The bucket's policies only
 * ever read segments 1 and 2 — the event and the owner — so the file name is
 * ours to choose, and choosing the reservation makes it knowable *before* the
 * take has been charged. That matters now that a take can come back 'waiting':
 * its clip row does not exist yet, and holding the recording hostage until an
 * unrelated member stopped filming would risk losing it to a killed app.
 */
export function clipStoragePath(eventId: string, userId: string, key: string): string {
  return `${eventId}/${userId}/${key}.mp4`;
}

/**
 * Attach a finished upload to its clip row.
 *
 * The clip row exists from the moment recording stops; the file lands later,
 * possibly much later on a bad venue network.
 */
export async function markClipUploaded(clipId: string, storagePath: string): Promise<void> {
  const { error } = await getSupabase()
    .from('clips')
    .update({ storage_path: storagePath, status: 'uploaded' })
    .eq('id', clipId);
  if (error) throw error;
}

/**
 * Move an event from 'setup' to 'live'.
 *
 * Screen 10's "Start the Event". A function rather than a direct UPDATE — the
 * host's RLS policy would also accept 'ready' -> 'setup' or a second start, and
 * the legal transition is exactly one arrow. Starting an already-live event is
 * a no-op that returns the row, so a double tap is harmless.
 */
export async function startEvent(eventId: string): Promise<Event> {
  const { data, error } = await getSupabase().rpc('start_event', { p_event_id: eventId });
  if (error) throw error;
  return data as unknown as Event;
}

/**
 * Move an event from 'live' to 'processing' — the group has run out of time.
 *
 * Called by whichever member's phone notices the budget is gone first. Every
 * other member's phone finds out from the realtime UPDATE and follows to screen
 * 14 on its own, which is what ends the event for the whole group rather than
 * for the one person who happened to be filming.
 *
 * Safe to call from several phones at once: already-processing returns the row
 * unchanged. The server refuses if any budget is genuinely left, so a client
 * cannot end everyone else's event early.
 */
export async function finishEvent(eventId: string): Promise<Event> {
  const { data, error } = await getSupabase().rpc('finish_event', { p_event_id: eventId });
  if (error) throw error;
  return data as unknown as Event;
}

/**
 * Move an event from 'processing' to 'ready' — the film is watchable.
 *
 * **This function produces no video, and its name is a leftover.** What 'ready'
 * means is "every clip that is coming has arrived, and the film can be watched
 * end to end" — 17 plays the clips back to back the moment it is true.
 *
 * **No video is produced anywhere.** There was briefly a second step behind this
 * one — a rendering API stitching the clips into a single mp4 — and it is gone.
 * Nothing in this project can run ffmpeg, and the clips played back to back were
 * always the real film; 'ready' is the only gate between the group and 17.
 *
 * Called from screen 14 once the uploads have landed (or once it has waited long
 * enough to stop holding the group up for one). Idempotent and callable by any
 * member, so every phone can call it without coordinating — see the migration.
 */
export async function compileFilm(eventId: string): Promise<Event> {
  const { data, error } = await getSupabase().rpc('compile_film', { p_event_id: eventId });
  if (error) throw error;
  return data as unknown as Event;
}

/**
 * Live roster updates — screen 10's chips appearing as guests join.
 *
 * Returns an unsubscribe function; call it on unmount. Modelled on
 * `subscribeToBudget` in ./budget.ts, down to the channel-naming convention.
 *
 * Listens to every event on the table rather than INSERT alone: a guest can also
 * rename themselves (`members: rename yourself`) or leave, and a roster that only
 * ever grew would be wrong in both cases. The callback is handed the whole new
 * list rather than a delta, because that is what the screen renders and it keeps
 * ordering in one place.
 */
export function subscribeToMembers(
  eventId: string,
  onChange: (members: EventMember[]) => void
): () => void {
  return subscribeToChanges(
    `event:${eventId}:members`,
    { event: '*', schema: 'public', table: 'event_members', filter: `event_id=eq.${eventId}` },
    () => {
      // Re-read rather than patching the payload in. A payload carries one row,
      // and reconstructing joined_at ordering from three event types is more
      // code and more bugs than one indexed query per change.
      void listMembers(eventId).then(onChange).catch(() => {
        // A failed refetch leaves the last good roster on screen, which is the
        // right outcome — the next change, or a remount, will correct it.
      });
    }
  );
}

/**
 * The other half of `startEvent()` — screen 12 waiting for the host.
 *
 * 10 flips `events.status` to 'live'; this is what notices. Reads the status
 * straight off the payload rather than refetching, which `replica identity full`
 * on `public.events` is what makes possible — the same reason `subscribeToBudget`
 * can read `used_seconds` without a round trip.
 *
 * A guest cannot poll for this: they have no reason to be looking at their phone
 * while they wait, so the transition has to come to them.
 */
export function subscribeToEventStatus(
  eventId: string,
  onChange: (status: Event['status']) => void
): () => void {
  return subscribeToChanges(
    `event:${eventId}:status`,
    { event: 'UPDATE', schema: 'public', table: 'events', filter: `id=eq.${eventId}` },
    (change) => {
      onChange((change.new as unknown as Event).status);
    }
  );
}

/**
 * Initials for a roster chip's avatar.
 *
 * One letter from the first word and one from the last — "Yuki Tanaka" -> "YT",
 * "Marcus" -> "M". Uppercased, and capped at two so a long name does not
 * overflow the 26px circle.
 */
export function initialsFor(name: string): string {
  const words = name.trim().split(/\s+/).filter(Boolean);
  if (words.length === 0) return '?';

  const first = words[0][0] ?? '';
  const last = words.length > 1 ? (words[words.length - 1][0] ?? '') : '';

  return (first + last).toUpperCase();
}

/**
 * Rebuild this user's purchase ledger from their store receipts.
 *
 * Settings' "Restore Purchases", and the second half of it: `restore()` in
 * lib/purchases.ts re-syncs the receipts up to RevenueCat, and this asks the
 * server to write whatever RevenueCat then holds into `public.purchases`.
 *
 * Both halves are needed. RevenueCat validates receipts but explicitly does not
 * track whether a *consumable* has been spent — that is our ledger's job — so a
 * reinstalled device with perfectly good receipts still has no rows here until
 * this runs, and would be asked to pay again for an event it already bought.
 *
 * Returns how many rows were genuinely new. Zero is an ordinary answer: nothing
 * to restore, or everything already recorded.
 */
export async function restorePurchases(): Promise<number> {
  const { data, error } = await getSupabase().functions.invoke('restore-purchases', {
    body: {},
  });
  if (error) throw await describeFunctionError(error);
  return (data as { restored?: number })?.restored ?? 0;
}

/**
 * Delete this account, the events it hosts, and the files behind them.
 *
 * Irreversible, and it takes other people's access with it: an event this user
 * hosts is deleted for every member of it. Clips they filmed in *other* people's
 * events are kept and unlinked from them — see the `delete-account` function and
 * the privacy notice for why footage inside someone else's film is not theirs to
 * withdraw.
 *
 * The caller is identified by their own JWT; no id crosses the wire. On success
 * the session is already dead server-side, so sign out locally and leave.
 */
export async function deleteAccount(): Promise<void> {
  const { error } = await getSupabase().functions.invoke('delete-account', { body: {} });
  if (error) throw await describeFunctionError(error);
}
